library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity instr_mems is
    generic (
        DEPTH : integer := 128
    );
    port (
        addr   : in  std_logic_vector(15 downto 0);
        instr0 : out std_logic_vector(15 downto 0);
        instr1 : out std_logic_vector(15 downto 0)
    );
end entity;

architecture rtl of instr_mems is

    -- 128 logical 16-bit entries -> 256 bytes
    type mem_array_t is array (0 to (DEPTH*2)-1) of std_logic_vector(7 downto 0);
    signal mem : mem_array_t;

begin

    init_proc : process
        variable i : integer;
    begin
        for i in 0 to (DEPTH*2)-1 loop
            mem(i) <= x"00";
        end loop;

        -- =====================================================
        -- Test 1: LLI + ADD (basic)
        -- =====================================================
        -- R1 = 5  →  LLI R1, 5  →  0011_001_000000101
        mem(0)  <= "00000101";  mem(1)  <= "00110010";

        -- R2 = 3  →  LLI R2, 3  →  0011_010_000000011
        mem(2)  <= "00000011";  mem(3)  <= "00110100";

        -- R3 = R1+R2 = 8  →  ADA R3,R1,R2  →  0001_001_010_011_000
        mem(4)  <= "10011000";  mem(5)  <= "00010010";

        -- =====================================================
        -- Test 2: Zero flag + ADZ
        -- =====================================================
        -- R4 = 0  →  LLI R4, 0  →  0011_100_000000000
        mem(6)  <= "00000000";  mem(7)  <= "00111000";

        -- R5 = R4+R4 = 0 → Z=1  →  ADA R5,R4,R4  →  0001_100_100_101_000
        mem(8)  <= "00101000";  mem(9)  <= "00011001";

        -- Executes (Z=1)  →  ADZ R6,R1,R2  →  0001_001_010_110_001
        mem(10) <= "10110001";  mem(11) <= "00010010";

        -- Should NOT execute (Z=0)  →  ADZ R7,R1,R2  →  0001_001_010_111_001
        mem(12) <= "10111001";  mem(13) <= "00010010";

        -- =====================================================
        -- Test 3: Carry flag + ADC
        -- =====================================================
        -- R1 = 0xFFFF  →  LLI R1, ffff  →  0011_001_111111111
        mem(14) <= "11111111";  mem(15) <= "00110011";

        -- R2 = 1  →  LLI R2, 1  →  0011_010_000000001
        mem(16) <= "00000001";  mem(17) <= "00110100";

        -- R3 = R1+R2 → carry  →  ADA R3,R1,R2  →  0001_001_010_011_000
        mem(18) <= "10011000";  mem(19) <= "00010010";

        -- Executes if carry=1  →  ADC R4,R3,R2  →  0001_011_010_100_010
        mem(20) <= "10100010";  mem(21) <= "00010110";

        -- R5 = ~(R1&R2)  →  NDU R5,R1,R2  →  0010_001_010_101_000
        mem(22) <= "10101000";  mem(23) <= "00100010";

        -- =====================================================
        -- Test 4: BEQ taken
        -- =====================================================
        -- if R1==R1 jump +2  →  BEQ R1,R1,+2  →  1000_001_001_000010
        mem(24) <= "01000010";  mem(25) <= "10000010";

        -- skipped  →  LLI R6,1  →  0011_110_000000001
        mem(26) <= "00000001";  mem(27) <= "00111100";

        -- executed  →  LLI R6,2  →  0011_110_000000010
        mem(28) <= "00000010";  mem(29) <= "00111100";

        -- =====================================================
        -- Test 5: JAL
        -- =====================================================
        -- R7=PC+1, PC+=2  →  JAL R7,+2  →  1100_111_000000010
        mem(30) <= "00000010";  mem(31) <= "11001110";

        -- skipped  →  LLI R1,7  →  0011_001_000000111
        mem(32) <= "00000111";  mem(33) <= "00110010";

        -- landing  →  LLI R1,8  →  0011_001_000001000
        mem(34) <= "00001000";  mem(35) <= "00110010";

        -- Jump to R7  →  JLR R0,R7  →  1101_111_111_000000
        mem(36) <= "11000000";  mem(37) <= "11011111";

        -- =====================================================
        -- Test 6: SW + LW (basic memory)
        -- =====================================================
        -- R1=10  →  LLI R1,10  →  0011_001_000001010
        mem(38) <= "00001010";  mem(39) <= "00110010";

        -- R2=21  →  LLI R2,21  →  0011_010_000010101
        mem(40) <= "00010101";  mem(41) <= "00110100";

        -- MEM[R1+0]=R2  →  SW R2,R1,0  →  0101_010_001_000000
        mem(42) <= "01000000";  mem(43) <= "01010100";

        -- R3=MEM[R1+0]  →  LW R3,R1,0  →  0100_011_001_000000
        mem(44) <= "01000000";  mem(45) <= "01000110";

        -- R4=R3+R2=42  →  ADA R4,R2,R3  →  0001_010_011_100_000
        mem(46) <= "11100000";  mem(47) <= "00010100";

        -- =====================================================
        -- Clear registers R1-R7
        -- =====================================================
        mem(48) <= "00000000";  mem(49) <= "00110010";
        mem(50) <= "00000000";  mem(51) <= "00110100";
        mem(52) <= "00000000";  mem(53) <= "00110110";
        mem(54) <= "00000000";  mem(55) <= "00111000";
        mem(56) <= "00000000";  mem(57) <= "00111010";
        mem(58) <= "00000000";  mem(59) <= "00111100";
        mem(60) <= "00000000";  mem(61) <= "00111110";

        -- =====================================================
        -- Hazard-stress program
        -- =====================================================
        -- R1=7  →  LLI R1,7  →  0011_001_000000111
        mem(62) <= "00000111";  mem(63) <= "00110010";
        
        -- R2=3  →  LLI R2,3  →  0011_010_000000011
        mem(64) <= "00000011";  mem(65) <= "00110100";
        
        -- R3=R1+R2=10  →  ADA R3,R1,R2  →  0001_001_010_011_000
        mem(66) <= "10011000";  mem(67) <= "00010010";
        
        -- MEM[R5+0]=R3  →  SW R3,R5,0  →  0101_011_101_000000
        mem(68) <= "01000000";  mem(69) <= "01010111";
        
        -- R4=MEM[R5+0]  →  LW R4,R5,0  →  0100_100_101_000000
        mem(70) <= "01000000";  mem(71) <= "01001001";
        
        -- R5=R4+R1 (load-use stall)  →  ADA R5,R4,R1  →  0001_100_001_101_000
        mem(72) <= "01101000";  mem(73) <= "00011000";
        
        -- R6=0, Z=1  →  ADA R6,R7,R7  →  0001_111_111_110_000
        mem(74) <= "11110000";  mem(75) <= "00011111";
        
        -- R5=R5+R2 (ADZ via flag fwd)  →  ADZ R5,R5,R2  →  0001_101_010_101_001
        mem(76) <= "10101001";  mem(77) <= "00011010";
        
        -- Branch on fwd regs (R4==R3)  →  BEQ R4,R3,+2  →  1000_100_011_000010
        mem(78) <= "11000010";  mem(79) <= "10001000";
        
        -- skipped  →  LLI R6,99  →  0011_110_000110011
        mem(80) <= "00110011";  mem(81) <= "00111100";
        
        -- executed  →  LLI R6,42  →  0011_110_000101010
        mem(82) <= "00101010";  mem(83) <= "00111100";
        
        -- Call fwd  →  JAL R7,+2  →  1100_111_000000010
        mem(84) <= "00000010";  mem(85) <= "11001110";
        
        -- skipped  →  LLI R1,111  →  0011_001_001101111
        mem(86) <= "01101111";  mem(87) <= "00110010";
        
        -- landing  →  LLI R1,110  →  0011_001_001101110
        mem(88) <= "01101110";  mem(89) <= "00110010";
        
        -- R7=96  →  LLI R7,96  →  0011_111_001100000
        mem(90) <= "01100000";  mem(91) <= "00111110";
        
        -- return → PC=96  →  JLR R0,R7  →  1101_000_111_000000
        mem(92) <= "11000000";  mem(93) <= "11010001";
        
        -- skipped  →  LLI R1,1  →  0011_001_000000001
        mem(94) <= "00000001";  mem(95) <= "00110010";

        -- =====================================================
        -- Clear registers R1-R7
        -- =====================================================
        mem(96)  <= "00000000"; mem(97)  <= "00110010";
        mem(98)  <= "00000000"; mem(99)  <= "00110100";
        mem(100) <= "00000000"; mem(101) <= "00110110";
        mem(102) <= "00000000"; mem(103) <= "00111000";
        mem(104) <= "00000000"; mem(105) <= "00111010";
        mem(106) <= "00000000"; mem(107) <= "00111100";
        mem(108) <= "00000000"; mem(109) <= "00111110";

        -- Ah shit, here we go again  →  JAL R7,-110
        mem(110) <= "11001001"; mem(111) <= "11001111";

        wait;
    end process;

    -- Combinational dual fetch from 4 consecutive bytes (little-endian)
    process(addr, mem)
        variable base : integer;
    begin
        base := to_integer(unsigned(addr(7 downto 0)));

        instr0 <= mem(base + 1) & mem(base);
        instr1 <= mem(base + 3) & mem(base + 2);
    end process;

end architecture;